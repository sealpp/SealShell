"""Generate offline file icons in their original Material Icon Theme colors.

Run: python scripts/generate_file_icons.py [--archive refs/material-icon-theme-5.39.0.tgz]
Source: https://github.com/material-extensions/vscode-material-icon-theme (MIT).
"""

import argparse
import base64
import hashlib
import io
import json
import posixpath
import re
import tarfile
import urllib.parse
import urllib.request
from pathlib import Path

VERSION = "5.39.0"
INTEGRITY = "6dUQXJgNBlklaILIOlCZXhSBTsBmLkt11XMoTY7Uyb4ZikelGgZHOY4AdOWBA+SXz51cVWfOVnTHrTwGM91eYw=="
URL = f"https://registry.npmjs.org/material-icon-theme/-/material-icon-theme-{VERSION}.tgz"
OUTPUT = Path(__file__).resolve().parents[1] / "shell/src/assets/file-icons"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in assets differ")
    args = parser.parse_args()
    if args.archive:
        archive = args.archive.read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=30) as response:
            archive = response.read()
    assert base64.b64encode(hashlib.sha512(archive).digest()).decode() == INTEGRITY, "Archive integrity mismatch"
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as package:
        manifest = json.load(package.extractfile("package/dist/material-icons.json"))
        rules = {key: {name.lower(): icon for name, icon in manifest[key].items()}
                 for key in ("fileNames", "fileExtensions", "folderNames")}
        rules.update(file=manifest["file"], folder=manifest["folder"])
        used = {rules["file"], rules["folder"]}
        for key in ("fileNames", "fileExtensions", "folderNames"):
            used.update(rules[key].values())
        css = [f"/* Generated by scripts/generate_file_icons.py from Material Icon Theme {VERSION}. MIT; see LICENSE. */"]
        for icon in sorted(used):
            assert re.fullmatch(r"[\w-]+", icon), icon
            name = posixpath.basename(manifest["iconDefinitions"][icon]["iconPath"])
            svg = package.extractfile("package/icons/" + name).read().decode()
            data = urllib.parse.quote(svg, safe="/=:,.-_")
            css.append(f'.file-icon[data-file-icon="{icon}"]{{--file-icon-image:url("data:image/svg+xml,{data}")}}')
        files = {
            "associations.json": json.dumps(rules, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            "icons.css": "\n".join(css) + "\n",
            "LICENSE": package.extractfile("package/LICENSE").read().decode(),
        }
    for name, content in files.items():
        data = content.replace("\r\n", "\n").encode()
        target = OUTPUT / name
        if args.check:
            assert target.read_bytes() == data, f"Regenerate {target}"
        else:
            OUTPUT.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    print(f"{len(used)} icons; {len(rules['fileNames'])} file names; "
          f"{len(rules['fileExtensions'])} extensions; {len(rules['folderNames'])} folder names")


if __name__ == "__main__":
    main()
