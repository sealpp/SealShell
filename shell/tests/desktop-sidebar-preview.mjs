import { expect } from '@playwright/test'
import { join } from 'node:path'

export async function verifyDesktopSidebarPreview(page, { artifacts }) {
  const activity = page.getByRole('button', { name: '会话', exact: true })
  const sidebar = page.locator('#connections-sidebar')
  const workArea = page.locator('.terminal-area')
  const pinnedBounds = await workArea.boundingBox()
  await activity.click()
  await expect(sidebar).toBeHidden()
  const freeBounds = await workArea.boundingBox()
  expect(freeBounds.width).toBeGreaterThan(pinnedBounds.width)
  const away = () => page.mouse.move(freeBounds.x + freeBounds.width - 20, freeBounds.y + 100)
  await away()
  await activity.hover()
  await expect(sidebar).toHaveClass(/floating/)
  await expect(sidebar).toBeVisible()
  expect(await workArea.boundingBox()).toEqual(freeBounds)
  await sidebar.locator('.conn-list').hover()
  await page.waitForTimeout(500)
  await expect(sidebar).toBeVisible()
  await page.screenshot({ path: join(artifacts, 'sidebar-preview.png') })
  await away()
  await expect(sidebar).toBeHidden()
  expect(await workArea.boundingBox()).toEqual(freeBounds)
  await activity.hover()
  await expect(sidebar).toBeVisible()
  await page.getByRole('button', { name: '固定会话侧栏', exact: true }).click()
  await expect(sidebar).not.toHaveClass(/floating/)
  await away()
  await page.waitForTimeout(500)
  await expect(sidebar).toBeVisible()
  expect(await workArea.boundingBox()).toEqual(pinnedBounds)
  console.log('Desktop sidebar: delayed hover preview, unchanged work area, pointer transfer, automatic close and pinning')
}
