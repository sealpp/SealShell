import { test, expect, type Page } from '@playwright/test'

test.beforeEach(async ({ page }) => { await page.goto('/tests/proxy-settings-harness.html') })
const settings = (page: Page) => page.getByRole('dialog', { name: '设置', exact: true })
const hostDialog = (page: Page) => page.getByRole('dialog', { name: '编辑主机', exact: true })
async function addProxy(page: Page) {
  await settings(page).getByRole('button', { name: '添加代理' }).click()
  await page.getByLabel('代理名称', { exact: true }).fill('Office')
  await page.getByLabel('代理类型', { exact: true }).selectOption('socks5')
  await page.getByLabel('代理地址', { exact: true }).fill('proxy.example')
  await expect(page.locator('.proxy-editor [role="status"]')).toHaveText('已自动保存')
}
async function closeSettings(page: Page) {
  await settings(page).getByRole('button', { name: '关闭', exact: true }).click()
  await expect(settings(page)).toBeHidden()
}

test('autosaves catalog and encrypted credentials while retaining the last valid configuration', async ({ page }) => {
  await addProxy(page)
  await expect(settings(page).getByRole('button', { name: /^(保存|确认|取消)$/ })).toHaveCount(0)
  await page.getByLabel('需要认证').check()
  await page.getByLabel('代理用户名', { exact: true }).fill('alice')
  await page.getByLabel('代理密码', { exact: true }).fill('fixture-password')
  await expect(page.locator('.proxy-editor [role="status"]')).toHaveText('已自动保存')
  await closeSettings(page)
  await page.reload()
  await page.getByRole('button', { name: '编辑 Office', exact: true }).click()
  await expect(page.locator('.proxy-secret')).toContainText('已保存')
  await expect(page.locator('input[type="password"]')).toHaveCount(0)
  await page.getByLabel('代理用户名', { exact: true }).fill('bob')
  await expect(page.locator('.proxy-editor [role="status"]')).toHaveText('已自动保存')
  const stored = await page.evaluate(async () => {
    const { store } = await import('/src/stores/app.ts')
    const { readCredential, readMeta } = await import('/src/services/storage.ts')
    const { proxyPassword } = await import('/src/services/proxy/profiles.ts')
    return { catalog: await readMeta('proxyServers'), record: await readCredential(`proxy:${store.proxies[0].id}`), retained: await proxyPassword({ kind: 'saved', id: store.proxies[0].id }) }
  })
  expect(stored.retained).toBe('fixture-password')
  expect(JSON.stringify(stored.catalog)).not.toContain('fixture-password')
  expect(JSON.stringify(stored.record)).not.toContain('fixture-password')
  await page.getByLabel('代理端口', { exact: true }).fill('0')
  await expect(page.locator('.proxy-editor [role="alert"]')).toContainText('1–65535')
  await closeSettings(page)
  await page.reload()
  await page.getByRole('button', { name: '编辑 Office', exact: true }).click()
  await expect(page.getByLabel('代理端口', { exact: true })).toHaveValue('1080')
  await page.locator('.proxy-secret').getByRole('button', { name: '清除', exact: true }).click()
  await expect(page.locator('.proxy-editor [role="status"]')).toHaveText('已自动保存')
  await page.reload()
  await page.getByRole('button', { name: '编辑 Office', exact: true }).click()
  await expect(page.getByLabel('代理密码', { exact: true })).toHaveValue('')
})

test('retains both host modes and disabled references, blocks deletion, and permits explicit unlinking', async ({ page }) => {
  await addProxy(page)
  const proxyId = await page.evaluate(async () => (await import('/src/stores/app.ts')).store.proxies[0].id)
  await closeSettings(page)
  await page.getByRole('button', { name: '编辑测试主机' }).click()
  const host = hostDialog(page)
  await host.getByLabel('使用代理').check()
  await host.getByLabel('代理地址', { exact: true }).fill('inline.example')
  await host.getByLabel('代理端口', { exact: true }).fill('3128')
  await host.getByRole('tab', { name: '从列表选择' }).click()
  await host.getByLabel('代理服务器', { exact: true }).selectOption(proxyId)
  await host.getByLabel('使用代理').uncheck()
  await host.getByRole('button', { name: '确认', exact: true }).click()
  await expect(host).toBeHidden()
  await page.getByRole('button', { name: '打开设置' }).click()
  await page.getByRole('button', { name: '删除 Office', exact: true }).click()
  await expect(page.locator('.proxy-references')).toContainText('Test server')
  await page.locator('.proxy-references').getByRole('button', { name: 'Test server' }).click()
  await expect(host.getByLabel('使用代理')).not.toBeChecked()
  await host.getByLabel('使用代理').check()
  await expect(host.getByLabel('代理服务器', { exact: true })).toHaveValue(proxyId)
  await host.getByLabel('代理服务器', { exact: true }).selectOption('')
  await host.getByRole('tab', { name: '直接填写' }).click()
  await expect(host.getByLabel('代理地址', { exact: true })).toHaveValue('inline.example')
  await expect(host.getByLabel('代理端口', { exact: true })).toHaveValue('3128')
  await host.getByRole('button', { name: '确认', exact: true }).click()
  await expect(host).toBeHidden()
  await page.getByRole('button', { name: '删除 Office', exact: true }).click()
  await page.getByRole('dialog', { name: '删除代理', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.proxy-row')).toHaveCount(0)
})

