import { expect, test, type Page } from '@playwright/test'

const sidebar = (page: Page) => page.locator('#connections-sidebar')
const activity = (page: Page) => page.getByRole('button', { name: '会话', exact: true })

async function openUnpinnedWorkbench(page: Page) {
  await page.goto('/tests/app-harness.html')
  await expect(page.locator('.conn-list')).toBeVisible()
  await page.evaluate(async () => {
    const { store } = await import('/src/stores/app.ts')
    store.hosts = Array.from({ length: 40 }, (_, index) => ({
      id: `preview-${index}`, name: `Server ${String(index).padStart(2, '0')}`,
      address: `192.0.2.${index + 1}`, port: 22, username: 'root', folderId: null,
    }))
  })
  await activity(page).click()
  await page.mouse.move(700, 300)
  await expect(sidebar(page)).toBeHidden()
}

async function showPreview(page: Page) {
  await activity(page).hover()
  await expect(sidebar(page)).toBeVisible()
  await expect(sidebar(page)).toHaveClass(/floating/)
}

test('waits before previewing, cancels a quick pass and preserves keyboard focus', async ({ page }) => {
  await openUnpinnedWorkbench(page)
  await page.clock.install()
  await page.locator('.workbench-menu-trigger').focus()
  await activity(page).hover()
  await page.clock.runFor(150)
  await expect(sidebar(page)).toBeHidden()
  await page.mouse.move(700, 300)
  await page.clock.runFor(500)
  await expect(sidebar(page)).toBeHidden()
  await activity(page).hover()
  await page.clock.runFor(400)
  await expect(sidebar(page)).toBeVisible()
  await expect(activity(page)).toHaveAttribute('aria-expanded', 'true')
  await expect(activity(page)).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.workbench-menu-trigger')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(sidebar(page)).toBeHidden()
  await expect(page.locator('.workbench-menu-trigger')).toBeFocused()
})

test('allows moving between the icon and panel and closes only after leaving both', async ({ page }) => {
  await openUnpinnedWorkbench(page)
  const before = await page.locator('.terminal-area').boundingBox()
  await showPreview(page)
  await page.locator('.conn-item').first().hover()
  await page.waitForTimeout(500)
  await expect(sidebar(page)).toBeVisible()
  await activity(page).hover()
  await page.waitForTimeout(500)
  await expect(sidebar(page)).toBeVisible()
  expect(await page.locator('.terminal-area').boundingBox()).toEqual(before)
  await expect(page.locator('.panel-resizer')).toHaveCount(0)
  await page.mouse.move(700, 300)
  await expect(sidebar(page)).toBeHidden()
  expect(await page.locator('.terminal-area').boundingBox()).toEqual(before)
  await expect(activity(page)).toHaveAttribute('aria-expanded', 'false')
})

test('pins and unpins the existing tree while preserving its selection and scroll position', async ({ page }) => {
  await openUnpinnedWorkbench(page)
  await showPreview(page)
  await page.locator('.conn-item').first().click()
  await page.locator('.conn-list').evaluate(element => { element.scrollTop = 100 })
  const initialScroll = await page.locator('.conn-list').evaluate(element => element.scrollTop)
  expect(initialScroll).toBeGreaterThan(0)
  await page.getByRole('button', { name: '固定会话侧栏', exact: true }).click()
  await expect(sidebar(page)).not.toHaveClass(/floating/)
  await expect(activity(page)).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.panel-resizer')).toBeVisible()
  await page.mouse.move(700, 300)
  await page.waitForTimeout(500)
  await expect(sidebar(page)).toBeVisible()
  expect(await page.locator('.conn-list').evaluate(element => element.scrollTop)).toBe(initialScroll)
  await expect(page.locator('.conn-item.selected')).toHaveText('Server 00')
  await page.getByRole('button', { name: '取消固定会话侧栏', exact: true }).click()
  await expect(sidebar(page)).toHaveClass(/floating/)
  expect(await page.locator('.conn-list').evaluate(element => element.scrollTop)).toBe(initialScroll)
  await page.mouse.move(700, 300)
  await expect(sidebar(page)).toBeHidden()
  await activity(page).click()
  await expect(sidebar(page)).toBeVisible()
  await expect(sidebar(page)).not.toHaveClass(/floating/)
  await activity(page).click()
  await expect(sidebar(page)).toBeHidden()
})

test('keeps the preview open while using a portalled context menu outside its bounds', async ({ page }) => {
  await openUnpinnedWorkbench(page)
  await showPreview(page)
  await page.locator('.conn-item').first().click({ button: 'right', position: { x: 205, y: 10 } })
  const edit = page.getByRole('menuitem', { name: '编辑', exact: true })
  await edit.hover()
  expect((await edit.boundingBox())!.x).toBeGreaterThanOrEqual((await sidebar(page).boundingBox())!.x + 200)
  await page.waitForTimeout(500)
  await expect(sidebar(page)).toBeVisible()
  await edit.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(sidebar(page)).toBeHidden()
})

test('closes after dismissing a menu outside the panel and restores focus from a hidden tree', async ({ page }) => {
  await openUnpinnedWorkbench(page)
  await showPreview(page)
  await page.locator('.conn-item').first().click({ button: 'right', position: { x: 205, y: 10 } })
  await page.getByRole('menuitem', { name: '编辑', exact: true }).hover()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(sidebar(page)).toBeHidden()
  await expect(activity(page)).toBeFocused()
  await page.mouse.move(700, 300)
  await showPreview(page)
  await page.locator('.conn-item').first().click()
  await page.keyboard.press('Escape')
  await expect(sidebar(page)).toBeHidden()
  await expect(activity(page)).toBeFocused()
})

test('clears a pending or visible preview when the window loses focus or a dialog opens', async ({ page }) => {
  await openUnpinnedWorkbench(page)
  await page.clock.install()
  await activity(page).hover()
  await page.clock.runFor(100)
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await page.clock.runFor(500)
  await expect(sidebar(page)).toBeHidden()
  await page.mouse.move(700, 300)
  await activity(page).hover()
  await page.clock.runFor(400)
  await expect(sidebar(page)).toBeVisible()
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await expect(sidebar(page)).toBeHidden()
  await page.mouse.move(700, 300)
  await activity(page).hover()
  await page.evaluate(async () => {
    const { store } = await import('/src/stores/app.ts')
    store.folderModalOpen = true
  })
  await page.clock.runFor(500)
  await expect(sidebar(page)).toBeHidden()
  await expect(page.getByRole('dialog')).toBeVisible()
})

test('fits a floating sidebar within a narrow viewport', async ({ page }) => {
  await openUnpinnedWorkbench(page)
  await page.setViewportSize({ width: 240, height: 500 })
  await showPreview(page)
  const bounds = (await sidebar(page).boundingBox())!
  expect(bounds.x).toBe(48)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(240)
  await expect(page.getByRole('button', { name: '固定会话侧栏', exact: true })).toBeInViewport()
})
