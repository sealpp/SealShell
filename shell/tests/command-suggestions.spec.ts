test('the production terminal shows the popup and sends clicked text through its session input path', async ({ page }) => {
  await page.route('**/src/services/ws.ts', route => route.fulfill({ contentType: 'application/javascript', body: `
    export * from '/src/services/ws.ts?actual';
    const encoder = new TextEncoder();
    let output;
    window.productionInputs = [];
    export function resizeTerminal() {}
    export function setTerminalOutputHandler(id, handler) {
      output = handler;
      if (handler) setTimeout(() => { handler(encoder.encode('dev@host:~$ ')); window.productionReady = true; }, 0);
    }
    export function sendTerminalInput(id, payload) {
      const text = new TextDecoder().decode(payload);
      window.productionInputs.push({ id, text });
      output?.(encoder.encode(text === '\\r' ? '\\r\\ndev@host:~$ ' : text));
    }
  ` }))
  await page.goto('/tests/terminal-suggestions-harness.html')
  await page.waitForFunction(() => (window as any).productionReady)
  await page.evaluate(async () => {
    const { rememberSuggestionCommand } = await import('/src/services/terminalSuggestions/runtime.ts')
    await rememberSuggestionCommand('production-host', 'git status')
    await rememberSuggestionCommand('production-host', 'git status')
    await rememberSuggestionCommand('production-host', 'git diff')
  })
  await focus(page)
  await page.keyboard.type('git ')
  await expect(first(page)).toHaveText('git status')
  const screenshotDirectory = join(tmpdir(), 'seal-e2e', 'command-suggestions')
  await mkdir(screenshotDirectory, { recursive: true })
  await page.screenshot({ path: join(screenshotDirectory, 'popup.png') })
  await page.screenshot({ path: join(screenshotDirectory, 'compact.png'), clip: { x: 16, y: 12, width: 520, height: 240 } })
  await candidate(page, 'git diff').click()
  expect(await page.evaluate(() => (window as any).productionInputs.at(-1))).toEqual({ id: 'production-session', text: 'diff' })
  await page.keyboard.press('Enter')
  await expect.poll(() => page.evaluate(async () => {
    const { readCommandHistory } = await import(/* @vite-ignore */ '/src/services/storage.ts')
    return readCommandHistory('production-host')
  })).toEqual([expect.objectContaining({ command: 'git diff', uses: 2 }), expect.objectContaining({ command: 'git status', uses: 2 })])
})
