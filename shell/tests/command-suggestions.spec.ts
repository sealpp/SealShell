test('coexists with remote gray suggestions and preserves the remote Right acceptance key', async ({ page }) => {
  await page.evaluate(() => (window as any).harness.echo(false))
  await write(page, '\x1b[?1h')
  await page.keyboard.type('git ')
  await write(page, 'git \x1b[90mstatus\x1b[0m\x1b[6D')
  await expect(first(page)).toHaveText('git status')
  await expect(page.locator('.terminal-command-hint')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).harness.text())).toContain('git status')
  await page.keyboard.press('ArrowRight')
  expect(await page.evaluate(() => (window as any).harness.sent.at(-1))).toBe('\x1bOC')
  await expect(list(page)).toHaveCount(0)
  await write(page, 'status\x1b[K')
  await page.keyboard.press('Enter')
  await write(page, '\r\ndev@host:~$ ')
  await expect.poll(() => readHistory(page)).toEqual([expect.objectContaining({ command: 'git status' })])
  await page.keyboard.type('git ')
  await write(page, 'git \x1b[90mstatus\x1b[0m\x1b[6D')
  await candidate(page, 'git diff').click()
  expect(await page.evaluate(() => (window as any).harness.sent.at(-1))).toBe('diff')
  await write(page, '\r\x1b[Kdev@host:~$ git diff')
  await page.keyboard.press('Enter')
  await write(page, '\r\ndev@host:~$ ')
  await expect.poll(() => readHistory(page)).toEqual(expect.arrayContaining([expect.objectContaining({ command: 'git diff' })]))
  expect((await readHistory(page)).some((entry: any) => entry.command.includes('diffstatus'))).toBe(false)
})

test('history ranks by frequency, persists across reload and stays scoped to its connection', async ({ page }) => {
  for (const [command, uses] of [['git log --all', 1], ['git log --all', 2], ['git diff --stat', 1]] as const) {
    await page.keyboard.type(command)
    await page.keyboard.press('Enter')
    await expect.poll(async () => (await readHistory(page)).find((entry: any) => entry.command === command)?.uses).toBe(uses)
  }
  await page.keyboard.type('git ')
  await expect(first(page)).toHaveText('git log --all')
  await expect(list(page).getByRole('option').first()).toContainText('本地历史 · 2 次')
  expect(await readHistory(page, 'suggestions-b')).toEqual([])
  await page.reload()
  await expect(page.locator('#ready')).toHaveText('true')
  await focus(page)
  await page.keyboard.type('git ')
  await expect(first(page)).toHaveText('git log --all')
  await reset(page)
  await page.evaluate(() => (window as any).harness.echo(false))
  await page.keyboard.insertText('echo 中文')
  await page.keyboard.press('Enter')
  expect((await readHistory(page)).some((entry: any) => entry.command.startsWith('echo'))).toBe(false)
  await write(page, 'echo 中文\r\ndev@host:~$ ')
  await expect.poll(async () => (await readHistory(page)).some((entry: any) => entry.command === 'echo 中文')).toBe(true)
})

test('passwords, opt-outs, continuation prompts, alternate screens and multiline paste stay outside suggestions', async ({ page }) => {
  await reset(page, 'Password: ')
  await page.evaluate(() => (window as any).harness.echo(false))
  await page.keyboard.type('git-secret-password')
  await page.keyboard.press('Enter')
  await expect(list(page)).toHaveCount(0)
  await reset(page)
  await page.keyboard.type('hidden-at-shell-prompt')
  await page.keyboard.press('Enter')
  await write(page, '\r\ndev@host:~$ ')
  expect(await readHistory(page)).toEqual([])
  await page.evaluate(() => (window as any).harness.echo(true))
  for (const [prompt, input] of [['> ', 'git '], ['dev@host:~$ ', ' git status']]) {
    await reset(page, prompt)
    await page.keyboard.type(input)
    await expect(list(page)).toHaveCount(0)
    await page.keyboard.press('Enter')
  }
  await reset(page)
  await write(page, '\x1b[?1049h$ ')
  await page.keyboard.type('git ')
  await expect(list(page)).toHaveCount(0)
  await page.keyboard.press('Enter')
  await reset(page)
  await page.evaluate(() => (window as any).harness.paste('echo one\necho two'))
  await page.keyboard.press('Enter')
  await expect(list(page)).toHaveCount(0)
  expect(await readHistory(page)).toEqual([])
})

